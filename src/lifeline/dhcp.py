"""Managed `dnsmasq` DHCP/RA/DNS server supervisor and IPv6 RA deprecation.

Generates a self-contained `/run/lifeline/dnsmasq.conf` from `LifelineConfig`,
validates it with `dnsmasq --test`, supervises the child process inside the
systemd unit's cgroup, parses lease files, and sends Router-Lifetime=0 ICMPv6
Router Advertisements when stepping down from PRIMARY mode so clients drop the
default route immediately.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass
import ipaddress
import logging
import os
from pathlib import Path
import shutil
import signal
import socket
import struct
import time
from typing import Optional

from lifeline.config import HostEntry, LifelineConfig
from lifeline.net_utils import get_iface_mac, run_cmd, run_cmd_sync
from lifeline.probe import mac_str_to_bytes

LOG = logging.getLogger("lifeline.dhcp")


@dataclass(frozen=True)
class LeaseRecord:
    expires_at: int
    mac: str
    ip: str
    hostname: str
    client_id: str

    @property
    def is_v6(self) -> bool:
        return ":" in self.ip


def parse_dnsmasq_leases(lease_file: Path, now_epoch: Optional[int] = None) -> list[LeaseRecord]:
    """Parse `/run/lifeline/dnsmasq.leases`, returning currently valid leases."""
    if not lease_file.exists():
        return []
    now_ts = int(time.time()) if now_epoch is None else now_epoch
    records: list[LeaseRecord] = []
    for raw_line in lease_file.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("duid "):
            continue
        parts = line.split()
        if len(parts) < 4:
            continue
        try:
            expires_at = int(parts[0])
        except ValueError:
            continue
        if expires_at != 0 and expires_at < now_ts:
            continue
        mac = parts[1].lower()
        ip_str = parts[2]
        hostname = "" if parts[3] == "*" else parts[3]
        client_id = parts[4] if len(parts) >= 5 else ""
        records.append(
            LeaseRecord(
                expires_at=expires_at,
                mac=mac,
                ip=ip_str,
                hostname=hostname,
                client_id=client_id,
            )
        )
    return records


def detect_upstream_dns_server() -> str:
    """Return upstream DNS target for dnsmasq (`127.0.0.53` if systemd-resolved stub is up)."""
    resolv = Path("/etc/resolv.conf")
    if resolv.exists():
        text = resolv.read_text(encoding="utf-8", errors="replace")
        if "127.0.0.53" in text:
            return "127.0.0.53"
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith("nameserver "):
                addr = stripped.split()[1]
                if addr not in ("127.0.0.1", "::1"):
                    return addr
    return "127.0.0.53"


def render_dnsmasq_config(
    cfg: LifelineConfig,
    eth_if: str,
    *,
    wifi_has_ipv6_default: bool,
    upstream_dns: Optional[str] = None,
) -> str:
    """Render `/run/lifeline/dnsmasq.conf` content for PRIMARY mode."""
    net = cfg.lan.eth_ip.network
    router_ip = str(cfg.lan.eth_ip.ip)
    netmask = str(net.netmask)
    net_addr = str(net.network_address)
    runtime_dir = cfg.dhcp.runtime_dir
    lease_file = runtime_dir / "dnsmasq.leases"
    pid_file = runtime_dir / "dnsmasq.pid"
    upstream = upstream_dns or detect_upstream_dns_server()

    if cfg.dhcp.dynamic_pool_start and cfg.dhcp.dynamic_pool_end:
        v4_range = (
            f"dhcp-range={cfg.dhcp.dynamic_pool_start},{cfg.dhcp.dynamic_pool_end},"
            f"{netmask},{cfg.dhcp.lease_time}"
        )
        v6_range = f"dhcp-range={cfg.lan.eth_ipv6_prefix.network_address},slaac,ra-names,64,{cfg.dhcp.lease_time}"
    else:
        v4_range = f"dhcp-range={net_addr},static,{netmask},{cfg.dhcp.lease_time}"
        v6_range = f"dhcp-range={cfg.lan.eth_ipv6_prefix.network_address},static,slaac,ra-names,64,{cfg.dhcp.lease_time}"

    lines = [
        "# Auto-generated by lifeline; do not edit by hand.",
        f"interface={eth_if}",
        "bind-dynamic",
        "except-interface=lo",
        "port=53",
        "domain-needed",
        "bogus-priv",
        "no-resolv",
        f"server={upstream}",
        f"dhcp-leasefile={lease_file}",
        f"pid-file={pid_file}",
        f"dhcp-script={cfg.dhcp.lease_hook}",
        "script-on-renewal",
        v4_range,
        f"dhcp-option=option:router,{router_ip}",
        f"dhcp-option=option:dns-server,{router_ip}",
        "log-dhcp",
    ]
    if cfg.dhcp.authoritative:
        lines.append("dhcp-authoritative")

    if cfg.forwarding.ipv6_mode == "ula_nat66":
        ra_lifetime = 60 if wifi_has_ipv6_default else 0
        lines.extend(
            [
                "enable-ra",
                v6_range,
                "dhcp-option=option6:dns-server,[::]",
                f"ra-param={eth_if},10,{ra_lifetime}",
            ]
        )

    for entry in cfg.hosts:
        lines.append(_format_dhcp_host_line(entry, cfg.forwarding.ipv6_mode == "ula_nat66"))

    return "\n".join(lines) + "\n"


def _format_dhcp_host_line(entry: HostEntry, include_ipv6: bool) -> str:
    parts = [entry.mac, str(entry.ipv4)]
    if include_ipv6:
        parts.append(f"[{entry.ipv6}]")
    if entry.hostname:
        parts.append(entry.hostname)
    return "dhcp-host=" + ",".join(parts)


def build_ra_deprecation_packet(src_mac: str) -> bytes:
    """Build an ICMPv6 Router Advertisement payload with Router Lifetime = 0.

    Sent via `AF_INET6 / SOCK_RAW / IPPROTO_ICMPV6` so the kernel fills IPv6
    headers and the ICMPv6 checksum automatically.
    """
    mac_b = mac_str_to_bytes(src_mac)
    # ICMPv6 RA header (16 bytes): type=134, code=0, cksum=0, cur_hop_limit=64,
    # flags=0, router_lifetime=0 (deprecate default router), reachable=0, retrans=0
    ra_hdr = struct.pack("!BBHBBHII", 134, 0, 0, 64, 0, 0, 0, 0)
    # Source Link-Layer Address option (type=1, length=1 unit of 8 bytes, 6-byte MAC)
    sll_opt = struct.pack("!BB6s", 1, 1, mac_b)
    return ra_hdr + sll_opt


def send_ra_deprecation(eth_if: str, count: int = 2) -> None:
    """Broadcast unsolicited Router Advertisements with Router Lifetime = 0 on `eth_if`."""
    mac = get_iface_mac(eth_if)
    if not mac:
        return
    try:
        ifindex = socket.if_nametoindex(eth_if)
        pkt = build_ra_deprecation_packet(mac)
        sock = socket.socket(socket.AF_INET6, socket.SOCK_RAW, socket.IPPROTO_ICMPV6)
        try:
            sock.setsockopt(socket.SOL_SOCKET, socket.SO_BINDTODEVICE, eth_if.encode("utf-8") + b"\x00")
            sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_MULTICAST_IF, struct.pack("@I", ifindex))
            sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_MULTICAST_HOPS, 255)
            for _ in range(count):
                sock.sendto(pkt, ("ff02::1", 0, 0, ifindex))
        finally:
            sock.close()
    except OSError as exc:
        LOG.debug("Failed sending IPv6 RA deprecation on %s: %s", eth_if, exc)


class DnsmasqSupervisor:
    """Starts, validates, reloads, and cleanly stops the managed `dnsmasq` child."""

    def __init__(self) -> None:
        self.proc: Optional[asyncio.subprocess.Process] = None
        self.current_conf_text: Optional[str] = None
        self.current_iface: Optional[str] = None
        self._runtime_dir: Optional[Path] = None
        self._drain_tasks: list[asyncio.Task] = []

    @property
    def is_running(self) -> bool:
        return self.proc is not None and self.proc.returncode is None

    async def _drain_stream(self, stream: Optional[asyncio.StreamReader], label: str) -> None:
        if stream is None:
            return
        try:
            while True:
                line = await stream.readline()
                if not line:
                    return
                text = line.decode("utf-8", "replace").rstrip()
                if text:
                    LOG.info("[dnsmasq %s] %s", label, text)
        except asyncio.CancelledError:
            return
        except Exception:
            return

    async def start_or_reload(
        self,
        cfg: LifelineConfig,
        eth_if: str,
        *,
        wifi_has_ipv6_default: bool,
    ) -> None:
        """Write config, validate with `dnsmasq --test`, and start or SIGHUP dnsmasq."""
        dnsmasq_bin = shutil.which("dnsmasq") or "/usr/sbin/dnsmasq"
        runtime_dir = cfg.dhcp.runtime_dir
        runtime_dir.mkdir(parents=True, exist_ok=True)
        conf_path = runtime_dir / "dnsmasq.conf"
        tmp_path = runtime_dir / "dnsmasq.conf.tmp"

        conf_text = render_dnsmasq_config(
            cfg, eth_if, wifi_has_ipv6_default=wifi_has_ipv6_default
        )
        if self.is_running and self.current_conf_text == conf_text and self.current_iface == eth_if:
            return

        tmp_path.write_text(conf_text, encoding="utf-8")
        test_res = await run_cmd([dnsmasq_bin, "--test", f"--conf-file={tmp_path}"])
        if test_res.returncode != 0:
            raise RuntimeError(f"dnsmasq --test failed: {test_res.stderr.strip()}")
        tmp_path.replace(conf_path)

        # If already running on the same interface with only hosts/RA changes, SIGHUP or restart
        if self.is_running:
            await self.stop(deprecate_ra=False)

        # Ensure any orphaned lifeline-managed dnsmasq is gone before starting a new one.
        self.cleanup_stale_pid(runtime_dir)

        env = os.environ.copy()
        env["LIFELINE_NFT_TABLE"] = cfg.forwarding.nft_table
        env["LIFELINE_FWD_POLICY"] = cfg.forwarding.policy
        env["LIFELINE_LEASE_FILE"] = str(runtime_dir / "dnsmasq.leases")
        env["LIFELINE_HOSTS_FILE"] = str(cfg.dhcp.hosts_file)
        # Ensure lease-hook can always import lifeline even when run from source tree
        src_root = str(Path(__file__).resolve().parents[1])
        existing_pp = env.get("PYTHONPATH", "")
        env["PYTHONPATH"] = f"{src_root}:{existing_pp}" if existing_pp else src_root

        self._runtime_dir = runtime_dir
        self.proc = await asyncio.create_subprocess_exec(
            dnsmasq_bin,
            "--keep-in-foreground",
            "--conf-file=" + str(conf_path),
            env=env,
            stdin=asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        self.current_conf_text = conf_text
        self.current_iface = eth_if
        await asyncio.sleep(0.25)
        if self.proc.returncode is not None:
            out, err = await self.proc.communicate()
            detail = err.decode("utf-8", "replace") or out.decode("utf-8", "replace")
            raise RuntimeError(f"dnsmasq exited immediately: {detail}")
        self._drain_tasks = [
            asyncio.create_task(self._drain_stream(self.proc.stdout, "stdout")),
            asyncio.create_task(self._drain_stream(self.proc.stderr, "stderr")),
        ]
        LOG.info("Started dnsmasq (pid=%d) on %s", self.proc.pid, eth_if)

    async def stop(self, *, deprecate_ra: bool = True) -> None:
        """Stop dnsmasq cleanly (optionally sending RA lifetime=0 first)."""
        if deprecate_ra and self.current_iface:
            send_ra_deprecation(self.current_iface)

        for task in self._drain_tasks:
            task.cancel()
        self._drain_tasks.clear()

        if self.proc is not None and self.proc.returncode is None:
            pid = self.proc.pid
            try:
                self.proc.send_signal(signal.SIGTERM)
                await asyncio.wait_for(self.proc.wait(), timeout=3.0)
            except asyncio.TimeoutError:
                LOG.warning("dnsmasq pid=%d ignored SIGTERM, sending SIGKILL", pid)
                self.proc.kill()
                await self.proc.wait()
            except ProcessLookupError:
                pass
            LOG.info("Stopped dnsmasq (pid=%d)", pid)

        self.proc = None
        self.current_conf_text = None
        if self._runtime_dir is not None:
            self.cleanup_stale_pid(self._runtime_dir)

    @staticmethod
    def find_managed_dnsmasq_pids(runtime_dir: Path, proc_root: Path = Path("/proc")) -> list[int]:
        """Find all running PIDs matching lifeline's `--conf-file=<runtime_dir>/dnsmasq.conf`."""
        pids: set[int] = set()
        conf_arg = f"--conf-file={runtime_dir / 'dnsmasq.conf'}"

        pid_file = runtime_dir / "dnsmasq.pid"
        if pid_file.exists():
            try:
                pid = int(pid_file.read_text(encoding="utf-8").strip())
                cmdline = (proc_root / str(pid) / "cmdline").read_text(encoding="utf-8", errors="replace")
                if "dnsmasq" in cmdline:
                    pids.add(pid)
            except (OSError, ValueError):
                pass

        if proc_root.exists():
            for entry in proc_root.iterdir():
                if not entry.name.isdigit():
                    continue
                try:
                    pid = int(entry.name)
                    if pid == os.getpid():
                        continue
                    raw_cmd = (entry / "cmdline").read_bytes()
                    args = [a.decode("utf-8", "replace") for a in raw_cmd.split(b"\x00") if a]
                    if args and "dnsmasq" in Path(args[0]).name and conf_arg in args:
                        pids.add(pid)
                except OSError:
                    continue
        return sorted(pids)

    @classmethod
    def cleanup_stale_pid(cls, runtime_dir: Path, proc_root: Path = Path("/proc")) -> None:
        """Kill any leftover lifeline-managed dnsmasq (by pid-file AND `/proc` cmdline)."""
        pids = cls.find_managed_dnsmasq_pids(runtime_dir, proc_root=proc_root)
        for pid in pids:
            LOG.info("Terminating leftover lifeline dnsmasq process pid=%d", pid)
            try:
                os.kill(pid, signal.SIGTERM)
            except ProcessLookupError:
                continue
            except OSError as exc:
                LOG.warning("Failed sending SIGTERM to dnsmasq pid=%d: %s", pid, exc)
                continue

            deadline = time.monotonic() + 2.0
            while time.monotonic() < deadline:
                try:
                    os.kill(pid, 0)
                except ProcessLookupError:
                    break
                time.sleep(0.1)
            else:
                LOG.warning("dnsmasq pid=%d still alive after SIGTERM; sending SIGKILL", pid)
                try:
                    os.kill(pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass

        try:
            (runtime_dir / "dnsmasq.pid").unlink(missing_ok=True)
        except OSError:
            pass
